#!/bin/bash
# Миграция SOUL.md: убрать опасную инструкцию "молчи если без упоминания".
#
# Старая формулировка в шаблоне team-агента провоцировала LLM писать
# слово «молчу» / «(нет @упоминания)» в чат вместо реального молчания
# (literal-following). Бридж и так фильтрует входящие — агент не должен
# перепроверять @-упоминание, ему нужно только отвечать когда позвали.
#
# Скрипт идемпотентен: если паттерн не найден — ничего не делает.
#
# Usage:
#   scripts/migrate_soul_mute.sh
#
# Запускается из update.sh один раз (маркер .migrated_soul_mute).

set -u

REPO_ROOT=$(git rev-parse --show-toplevel 2>/dev/null)
if [ -z "$REPO_ROOT" ]; then
    echo "error: не в git-репозитории" >&2
    exit 1
fi
cd "$REPO_ROOT"

# Сигнатура старого блока — присутствует только в SOUL.md, который
# реально страдает от literal-following. Generic SOUL'ы из хардкода
# agent_manager.SOUL_MD_TEMPLATE этого блока не содержат.
PATTERN='В остальных случаях — молчи'

# Замена: сохраняем смысл «бот отвечает выборочно», но добавляем
# явное правило не писать слово «молчу» в чат.
NEW_BLOCK='## Непрерывное чтение, выборочные ответы

Бридж на стороне Python сам решает, передать тебе сообщение или нет.
Ты получаешь turn только когда:
1. Тебя тегнули (`@username`) — бридж снимает `@username` из текста перед
   передачей, поэтому в видимом тебе тексте символа `@` уже нет.
2. Сделали reply на твоё сообщение.
3. Сработал cron или напоминание.

**Если до тебя дошёл turn — отвечай нормально.** Не пытайся
перепроверять «есть ли `@` в тексте» и не пиши слова «молчу» / «нет
упоминания» / «не вижу @» — это команда тебе не отвечать, а не текст
в чат. Молчание реализуется на уровне бриджа, не на твоём.

Всё прочитанное в группе всё равно попадает в память через тихое
логирование и обрабатывается Dream-проходами — твоя задача только
ответить, когда тебя позвали.'

PATCHED=0
SKIPPED=0
TOTAL=0

# Iterate over all agent SOUL.md (in gitignore — живут только локально)
shopt -s nullglob
for soul in agents/*/SOUL.md; do
    TOTAL=$((TOTAL + 1))

    if ! grep -qF "$PATTERN" "$soul" 2>/dev/null; then
        SKIPPED=$((SKIPPED + 1))
        continue
    fi

    # Бэкап рядом — на случай если пользователь хочет посмотреть что было.
    cp -p "$soul" "${soul}.pre-mute-fix.bak"

    # Используем Python для надёжной замены multi-line блока.
    # awk/sed на bash 3.2 (macOS) с многострочной заменой — больно.
    python3 - "$soul" <<'PY'
import re
import sys

path = sys.argv[1]
with open(path, "r", encoding="utf-8") as f:
    content = f.read()

# Старый блок: от заголовка "## Непрерывное чтение..." до начала
# следующего ## заголовка (или конца файла). Захватываем целиком,
# чтобы не оставить остатки.
new_block = """## Непрерывное чтение, выборочные ответы

Бридж на стороне Python сам решает, передать тебе сообщение или нет.
Ты получаешь turn только когда:
1. Тебя тегнули (`@username`) — бридж снимает `@username` из текста перед
   передачей, поэтому в видимом тебе тексте символа `@` уже нет.
2. Сделали reply на твоё сообщение.
3. Сработал cron или напоминание.

**Если до тебя дошёл turn — отвечай нормально.** Не пытайся
перепроверять «есть ли `@` в тексте» и не пиши слова «молчу» / «нет
упоминания» / «не вижу @» — это команда тебе не отвечать, а не текст
в чат. Молчание реализуется на уровне бриджа, не на твоём.

Всё прочитанное в группе всё равно попадает в память через тихое
логирование и обрабатывается Dream-проходами — твоя задача только
ответить, когда тебя позвали.
"""

# Pattern: header "## Непрерывное чтение..." + всё до следующего "##"
# (на той же или меньшей вложенности) или конца файла.
pattern = re.compile(
    r"## Непрерывное чтение[^\n]*\n.*?(?=\n## |\Z)",
    re.DOTALL,
)

new_content, n = pattern.subn(new_block.rstrip() + "\n", content, count=1)
if n == 0:
    # Фолбэк: блок не нашли по заголовку — значит формулировка
    # размещена иначе. Не трогаем, оставляем оригинал.
    sys.exit(2)

with open(path, "w", encoding="utf-8") as f:
    f.write(new_content)
PY
    rc=$?
    if [ $rc -eq 0 ]; then
        PATCHED=$((PATCHED + 1))
        echo "  ✓ patched: $soul (бэкап: ${soul}.pre-mute-fix.bak)"
    else
        SKIPPED=$((SKIPPED + 1))
        # Откатить бэкап, чтобы не оставить мусор
        rm -f "${soul}.pre-mute-fix.bak"
        echo "  ○ skipped: $soul (паттерн заголовка не найден)"
    fi
done
shopt -u nullglob

echo "  total=${TOTAL}, patched=${PATCHED}, skipped=${SKIPPED}"
exit 0
